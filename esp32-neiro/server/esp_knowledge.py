"""База знаний ESP32 для системного промпта и LLM."""

ESP32_HARDWARE_KNOWLEDGE = """
## Возможности ESP32 (прошивка v2.0)

Ты управляешь ESP32 через инструменты. Прошивка умеет ВСЁ ниже — не говори, что «мигание не заложено» или «только вкл/выкл».

### GPIO
- Разрешены: 2,4,5,12-19,23,25-27,32,33
- ЗАПРЕЩЕНЫ: 6-11 (flash), 21-22 (I2C), 34-39 (только вход)
- GPIO 2 — встроенный LED, **active-low** (LOW=включен). Для GPIO2 всегда active_low=true

### Сигналы (generate_pin_signal)
Формы: square (меандр), sine (синус), saw (пила), triangle (треугольник)
- hz: 0.01–500 Гц (для LED обычно 0.1–50)
- duration_sec: длительность; 0 = бесконечно до stop_pin
- duty: яркость/скважность 0–100%
- «помигай», «синус 2 Гц», «пила 10 Гц 1 минуту» → generate_pin_signal

### ШИМ (set_pwm_output)
Постоянный PWM на пине: частота + duty%

### Остановка (stop_pin)
Остановить сигнал/ШИМ на пине

### Расписание (schedule_gpio_at_time) — выполняет СЕРВЕР
Абсолютное время: «13:30», «в 14:50», «2026-07-10 09:00»
Сервер поставит команду в очередь ESP32 в нужный момент (часы сервера/homeserv)

### Последовательность (run_pin_sequence)
Несколько действий с задержками: [{delay_ms, action}, ...]

### Дисплей I2C
OLED 0x3C, LCD 0x27

Правила:
- Мигание = square signal, не digital_write
- Расписание «в 13:30 включи» = schedule_gpio_at_time, не ждать LLM
- Сложные сценарии = sequence или несколько schedule
"""

